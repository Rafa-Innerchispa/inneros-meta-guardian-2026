class MetaProviderRegistry:
    """Read-only and governed provider registry for InnerOS Meta Ecosystem."""

    @classmethod
    def list_providers(cls) -> list[dict[str, Any]]:
        return [deepcopy(v) for v in META_CATALOG.values()]

    @classmethod
    def get_provider(cls, provider_key: str) -> dict[str, Any] | None:
        p = META_CATALOG.get(provider_key)
        return deepcopy(p) if p else None

    @classmethod
    def get_ecosystem_summary(cls) -> dict[str, Any]:
        items = list(META_CATALOG.values())
        return {
            "total_catalog_models": len(items),
            "tested_and_ready": len([i for i in items if i["status"] == "TESTED"]),
            "installed_locally": len([i for i in items if i["status"] in ("INSTALLED", "TESTED")]),
            "integrated_adapters": len([i for i in items if i["status"] == "INTEGRATED"]),
            "deferred_limitations": len([i for i in items if i["status"] == "DEFERRED"]),
            "timestamp": datetime.now(timezone.utc).isoformat(),
        }

